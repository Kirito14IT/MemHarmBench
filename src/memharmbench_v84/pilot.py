"""Frozen V8.4.3 attack-only cohort selection.

The historical module name is retained because the runtime imports it, but V8.4.3 has no
pilot or clean arm. It exposes the full 288-case cohort and an isolated four-case
qualification cohort in manifest order.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Iterable

CONDITIONS = ("attack",)
REPETITIONS = (1,)
FULL_CATALOG = "catalogs/full288_attack.json"
QUALIFICATION_CATALOG = "catalogs/smoke4.json"
PREFLIGHT_CASE_IDS: tuple[str, ...] = ()


def condition_root(root: Path, condition: str) -> Path:
    if condition != "attack":
        raise ValueError("V8.4.3 formal release is attack-only")
    return Path(root)


def dataset_root(root: Path) -> Path:
    return Path(root)


def condition_of(root: Path) -> str:
    path = Path(root) / "cases" / "catalog.json"
    try:
        raw = json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as error:
        raise ValueError(f"{path}: cannot read case catalog") from error
    if raw.get("condition") != "attack":
        raise ValueError("V8.4.3 case catalog must declare the attack condition")
    return "attack"


def cohort_manifest(root: Path, *, qualification: bool = False) -> dict[str, Any]:
    name = QUALIFICATION_CATALOG if qualification else FULL_CATALOG
    path = dataset_root(root) / name
    try:
        document = json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as error:
        raise ValueError(f"{path}: cannot read frozen cohort") from error
    expected = 4 if qualification else 288
    ids = document.get("case_ids")
    if (document.get("condition") != "attack" or document.get("repetitions") != [1]
            or not isinstance(ids, list) or len(ids) != expected or len(set(ids)) != expected):
        raise ValueError(f"{path}: invalid frozen V8.4.3 cohort")
    return document


def cohort_case_ids(root: Path, *, qualification: bool = False) -> list[str]:
    return list(cohort_manifest(root, qualification=qualification)["case_ids"])


def _case_id(case: Any) -> str:
    return case["case_id"] if isinstance(case, dict) else case.case_id


def _provenance(case: Any) -> dict[str, Any]:
    return (case.get("provenance", {}) if isinstance(case, dict) else case.provenance) or {}


def declared_condition(cases: Iterable[Any]) -> str:
    values = {_provenance(case).get("condition") for case in cases}
    if values != {"attack"}:
        raise ValueError(f"V8.4.3 catalog must contain only declared attack cases; found {values}")
    return "attack"


def select_cohort(cases: Iterable[Any], root: Path, *, qualification: bool = False) -> list[Any]:
    cases = list(cases)
    if not cases or declared_condition(cases) != condition_of(root):
        raise ValueError("V8.4.3 case catalog is empty or has a condition mismatch")
    by_id = {_case_id(case): case for case in cases}
    if len(cases) != 288 or len(by_id) != 288:
        raise ValueError("V8.4.3 source catalog must contain exactly 288 unique attack cases")
    ids = cohort_case_ids(root, qualification=qualification)
    missing = [case_id for case_id in ids if case_id not in by_id]
    if missing:
        raise ValueError("Frozen cohort names missing cases: " + ", ".join(missing))
    return [by_id[case_id] for case_id in ids]


# Compatibility aliases used by generic helpers. They select the full cohort only.
def pilot_manifest(root: Path) -> dict[str, Any]:
    return cohort_manifest(root)


def pilot_case_ids(root: Path, condition: str = "attack") -> list[str]:
    if condition != "attack":
        raise ValueError("V8.4.3 formal release is attack-only")
    return cohort_case_ids(root)


def select_pilot(cases: Iterable[Any], root: Path, condition: str = "attack") -> list[Any]:
    if condition != "attack":
        raise ValueError("V8.4.3 formal release is attack-only")
    return select_cohort(cases, root)


select_pilot_cases = select_pilot


def build_pilot_manifest(root: Path) -> dict[str, Any]:
    raise NotImplementedError("V8.4.3 cohort manifests are generated by scripts/build_release_manifest.py")


